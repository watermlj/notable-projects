function [theta1, theta2, omega1, omega2, gamma1, gamma2] = ...
    RK4_Algorithm(mass1, mass2, length1, length2, g, n, h, ...
    theta1, theta2, omega1, omega2, gamma1, gamma2)

    time = 0;

    for i = 2:(n + 1)

        k1 = [omega1(i - 1, 2), omega2(i - 1, 2), ...
            gamma1(i - 1, 2), gamma2(i - 1, 2)];
        k2 = [omega1(i - 1, 2) + (h / 2) * k1(3), ...
            omega2(i - 1, 2) + (h / 2) * k1(4), ...
            Gamma1(mass1, mass2, length1, length2, ...
            theta1(i - 1, 2) + (h / 2) * k1(1), ...
            theta2(i - 1, 2) + (h / 2) * k1(2), ...
            omega1(i - 1, 2) + (h / 2) * k1(3), ...
            omega2(i - 1, 2) + (h / 2) * k1(4), g), ...
            Gamma2(mass1, mass2, length1, length2, ...
            theta1(i - 1, 2) + (h / 2) * k1(1), ...
            theta2(i - 1, 2) + (h / 2) * k1(2), ...
            omega1(i - 1, 2) + (h / 2) * k1(3), ...
            omega2(i - 1, 2) + (h / 2) * k1(4), g)];
        k3 = [omega1(i - 1, 2) + (h / 2) * k2(3), ...
            omega2(i - 1, 2) + (h / 2) * k2(4), ...
            Gamma1(mass1, mass2, length1, length2, ...
            theta1(i - 1, 2) + (h / 2) * k2(1), ...
            theta2(i - 1, 2) + (h / 2) * k2(2), ...
            omega1(i - 1, 2) + (h / 2) * k2(3), ...
            omega2(i - 1, 2) + (h / 2) * k2(4), g) ...
            Gamma2(mass1, mass2, length1, length2, ...
            theta1(i - 1, 2) + (h / 2) * k2(1), ...
            theta2(i - 1, 2) + (h / 2) * k2(2), ...
            omega1(i - 1, 2) + (h / 2) * k2(3), ...
            omega2(i - 1, 2) + (h / 2) * k2(4), g)];
        k4 = [omega1(i - 1, 2) + h * k3(3), ...
            omega2(i - 1, 2) + h * k3(4), ...
            Gamma1(mass1, mass2, length1, length2, ...
            theta1(i - 1, 2) + h * k3(1), ...
            theta2(i - 1, 2) + h * k3(2), ...
            omega1(i - 1, 2) + h * k3(3), ...
            omega2(i - 1, 2) + h * k3(4), g), ...
            Gamma2(mass1, mass2, length1, length2, ...
            theta1(i - 1, 2) + h * k3(1), ...
            theta2(i - 1, 2) + h * k3(2), ...
            omega1(i - 1, 2) + h * k3(3), ...
            omega2(i - 1, 2) + h * k3(4), g)];

        time = time + h;
        [theta1(i, 1), theta2(i, 1), omega1(i, 1), omega2(i, 1), ...
            gamma1(i, 1), gamma2(i, 1)] = deal(time);

        theta1(i, 2) = theta1(i - 1, 2) + ...
            (h / 6) * (k1(1) + 2 * k2(1) + 2 * k3(1) + k4(1));
        theta2(i, 2) = theta2(i - 1, 2) + ...
            (h / 6) * (k1(2) + 2 * k2(2) + 2 * k3(2) + k4(2));
        omega1(i, 2) = omega1(i - 1, 2) + ...
            (h / 6) * (k1(3) + 2 * k2(3) + 2 * k3(3) + k4(3));
        omega2(i, 2) = omega2(i - 1, 2) + ...
            (h / 6) * (k1(4) + 2 * k2(4) + 2 * k3(4) + k4(4));
        gamma1(i, 2) = Gamma1(mass1, mass2, length1, length2, ...
            theta1(i, 2), theta2(i, 2), omega1(i, 2), omega2(i, 2), g);
        gamma2(i, 2) = Gamma2(mass1, mass2, length1, length2, ...
            theta1(i, 2), theta2(i, 2), omega1(i, 2), omega2(i, 2), g);

    end

end